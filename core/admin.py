from django.contrib import admin
from django.contrib.auth.admin import UserAdmin

from .models import AccessRequest, FileShare, DownloadEvent, EncryptedValue, FileCiphertext, PersonalData, StoredFile, User, UserKeyPair


@admin.register(StoredFile)
class StoredFileAdmin(admin.ModelAdmin):
    list_display = ("id", "category", "owner", "plaintext_size", "created_at")
    list_filter = ("category",)
    search_fields = ("owner__username",)


@admin.register(FileCiphertext)
class FileCiphertextAdmin(admin.ModelAdmin):
    list_display = ("id", "file", "algorithm", "mode", "ciphertext_size", "cipher_ms")
    list_filter = ("algorithm", "mode")


@admin.register(EncryptedValue)
class EncryptedValueAdmin(admin.ModelAdmin):
    list_display = ("id", "personal_data", "field_name", "algorithm", "mode", "ciphertext_size")
    list_filter = ("algorithm", "field_name")


@admin.register(DownloadEvent)
class DownloadEventAdmin(admin.ModelAdmin):
    list_display = ("id", "file", "algorithm", "success", "key_derivation_ms", "cipher_ms", "created_at")
    list_filter = ("algorithm", "success")


@admin.register(FileShare)
class FileShareAdmin(admin.ModelAdmin):
    list_display = ("id", "file", "doctor", "expires_at", "access_count")


@admin.register(UserKeyPair)
class UserKeyPairAdmin(admin.ModelAdmin):
    """Public fields only: the encrypted private key, salt and nonce are not shown."""

    list_display = ("id", "user", "purpose", "algorithm", "fingerprint", "active", "created_at")
    list_filter = ("purpose", "active")
    search_fields = ("user__username", "fingerprint")
    fields = (
        "user",
        "purpose",
        "algorithm",
        "fingerprint",
        "public_key_pem",
        "certificate_pem",
        "active",
        "generation_ms",
        "created_at",
    )
    readonly_fields = fields

    def has_add_permission(self, request):
        # Pairs are generated by the app with the user's password, never by hand.
        return False


@admin.register(AccessRequest)
class AccessRequestAdmin(admin.ModelAdmin):
    list_display = ("id", "requester", "owner", "category", "status", "created_at", "decided_at")
    list_filter = ("status", "category")
    search_fields = ("requester__username", "owner__username")


admin.site.register(PersonalData)
try:
    admin.site.register(User, UserAdmin)
except admin.sites.AlreadyRegistered:  # pragma: no cover - Django may register it
    pass
